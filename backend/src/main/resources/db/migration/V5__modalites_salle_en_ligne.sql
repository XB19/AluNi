-- Deux façons de suivre une formation :
--   SALLE    : cours donné à l'Académie (support PDF), examen lors d'une session programmée, une seule tentative ;
--   EN_LIGNE : modules suivis à son rythme, examen ouvert à tout moment une fois les modules terminés,
--              tentatives illimitées jusqu'à la réussite.

alter table enrollments add column mode varchar(20);
update enrollments e set mode = case when u.profile_type = 'INTERNE' then 'SALLE' else 'EN_LIGNE' end
from users u where u.id = e.user_id;
alter table enrollments alter column mode set not null;
alter table enrollments add constraint ck_enrollments_mode check (mode in ('SALLE', 'EN_LIGNE'));

-- Support de cours (PDF) téléchargé par les apprenants en salle
alter table courses add column support_url varchar(255);

-- Sessions d'examen programmées par le formateur pour ses apprenants en salle
create table exam_sessions (
    id          bigint generated by default as identity primary key,
    exam_id     bigint not null constraint fk_exam_sessions_exam references exams on delete cascade,
    starts_at   timestamp(6) with time zone not null,
    ends_at     timestamp(6) with time zone not null,
    created_at  timestamp(6) with time zone not null,
    constraint ck_exam_sessions_period check (ends_at > starts_at)
);
create index ix_exam_sessions_exam on exam_sessions (exam_id, starts_at);

-- Le nombre de tentatives et les dates d'ouverture découlent désormais de la modalité (et des sessions)
alter table exams drop column attempts_allowed;
alter table exams drop column opens_at;
alter table exams drop column closes_at;
