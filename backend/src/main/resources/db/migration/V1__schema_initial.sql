-- ALuNI : schéma initial de la plateforme e-learning et de certification

-- ---------------------------------------------------------------- Comptes
create table users (
    id              bigint generated by default as identity primary key,
    first_name      varchar(80)  not null,
    last_name       varchar(80)  not null,
    birth_date      date,
    gender          varchar(1),
    phone           varchar(20)  constraint uk_users_phone unique,
    email           varchar(160) constraint uk_users_email unique,
    password_hash   varchar(255) not null,
    role            varchar(20)  not null constraint ck_users_role check (role in ('APPRENANT', 'FORMATEUR', 'ADMIN')),
    profile_type    varchar(20)  constraint ck_users_profile check (profile_type in ('INTERNE', 'AUTRE_CDEJ', 'PARTICULIER')),
    center_name     varchar(160),
    speciality      varchar(160),
    title           varchar(160),
    bio             text,
    photo_url       varchar(255),
    status          varchar(20)  not null constraint ck_users_status check (status in ('EN_ATTENTE', 'ACTIF', 'SUSPENDU', 'REFUSE')),
    created_at      timestamp(6) with time zone not null,
    last_login_at   timestamp(6) with time zone
);

create table password_reset_codes (
    id          bigint generated by default as identity primary key,
    user_id     bigint       not null constraint fk_reset_user references users on delete cascade,
    code_hash   varchar(255) not null,
    expires_at  timestamp(6) with time zone not null,
    attempts    integer      not null,
    used        boolean      not null,
    created_at  timestamp(6) with time zone not null
);
create index ix_reset_user on password_reset_codes (user_id);

-- ---------------------------------------------------------------- Catalogue
create table categories (
    id        bigint generated by default as identity primary key,
    slug      varchar(80)  not null constraint uk_categories_slug unique,
    name      varchar(120) not null,
    icon      varchar(40),
    color     varchar(80),
    position  integer      not null
);

create table courses (
    id                 bigint generated by default as identity primary key,
    slug               varchar(160) not null constraint uk_courses_slug unique,
    title              varchar(200) not null,
    short_description  varchar(500),
    description        text,
    category_id        bigint       not null constraint fk_courses_category references categories,
    level              varchar(20)  not null constraint ck_courses_level check (level in ('DEBUTANT', 'INTERMEDIAIRE', 'AVANCE')),
    hours              integer      not null,
    weeks              integer      not null,
    trainer_id         bigint       not null constraint fk_courses_trainer references users,
    image_url          varchar(255),
    access             varchar(20)  not null constraint ck_courses_access check (access in ('LIBRE', 'VALIDATION')),
    status             varchar(20)  not null constraint ck_courses_status check (status in ('BROUILLON', 'EN_VALIDATION', 'PUBLIEE', 'REFUSEE', 'ARCHIVEE')),
    rating             float(53)    not null,
    popular            boolean      not null,
    featured_new       boolean      not null,
    prerequisites      jsonb        not null,
    objectives         jsonb        not null,
    skills             jsonb        not null,
    cert_types         jsonb        not null,
    review_comment     text,
    created_at         timestamp(6) with time zone not null,
    updated_at         timestamp(6) with time zone,
    submitted_at       timestamp(6) with time zone
);
create index ix_courses_category on courses (category_id);
create index ix_courses_trainer on courses (trainer_id);
create index ix_courses_status on courses (status);

create table course_modules (
    id         bigint generated by default as identity primary key,
    course_id  bigint       not null constraint fk_modules_course references courses on delete cascade,
    position   integer      not null,
    title      varchar(200) not null
);
create index ix_modules_course on course_modules (course_id);

create table lessons (
    id         bigint generated by default as identity primary key,
    module_id  bigint       not null constraint fk_lessons_module references course_modules on delete cascade,
    position   integer      not null,
    title      varchar(200) not null,
    type       varchar(20)  not null constraint ck_lessons_type check (type in ('VIDEO', 'TEXTE', 'PDF', 'IMAGE')),
    duration   varchar(40),
    content    text,
    video_url  varchar(255),
    file_url   varchar(255),
    practical  boolean      not null
);
create index ix_lessons_module on lessons (module_id);

-- ---------------------------------------------------------------- Apprentissage
create table enrollments (
    id            bigint generated by default as identity primary key,
    user_id       bigint      not null constraint fk_enrollments_user references users on delete cascade,
    course_id     bigint      not null constraint fk_enrollments_course references courses on delete cascade,
    status        varchar(20) not null constraint ck_enrollments_status check (status in ('EN_ATTENTE', 'ACTIF', 'REFUSE')),
    enrolled_at   timestamp(6) with time zone not null,
    decided_at    timestamp(6) with time zone,
    completed_at  timestamp(6) with time zone,
    constraint uk_enrollments_user_course unique (user_id, course_id)
);
create index ix_enrollments_course on enrollments (course_id);

create table lesson_progress (
    id            bigint generated by default as identity primary key,
    user_id       bigint not null constraint fk_progress_user references users on delete cascade,
    lesson_id     bigint not null constraint fk_progress_lesson references lessons on delete cascade,
    completed_at  timestamp(6) with time zone not null,
    constraint uk_progress_user_lesson unique (user_id, lesson_id)
);
create index ix_progress_lesson on lesson_progress (lesson_id);

create table quiz_results (
    id         bigint generated by default as identity primary key,
    user_id    bigint  not null constraint fk_quiz_user references users on delete cascade,
    module_id  bigint  not null constraint fk_quiz_module references course_modules on delete cascade,
    score      integer not null,
    taken_at   timestamp(6) with time zone not null,
    constraint uk_quiz_user_module unique (user_id, module_id)
);
create index ix_quiz_module on quiz_results (module_id);

-- ---------------------------------------------------------------- Évaluation
create table questions (
    id                bigint generated by default as identity primary key,
    course_id         bigint      not null constraint fk_questions_course references courses on delete cascade,
    module_id         bigint      constraint fk_questions_module references course_modules on delete cascade,
    type              varchar(20) not null constraint ck_questions_type check (type in ('UNIQUE', 'MULTIPLE', 'VRAIFAUX', 'COURTE', 'PRATIQUE')),
    text              text        not null,
    options           jsonb       not null,
    correct_answers   jsonb       not null,
    accepted_answers  jsonb       not null,
    points            integer     not null,
    created_at        timestamp(6) with time zone not null
);
create index ix_questions_course on questions (course_id);
create index ix_questions_module on questions (module_id);

create table exams (
    id                         bigint generated by default as identity primary key,
    course_id                  bigint       not null constraint uk_exams_course unique
                                            constraint fk_exams_course references courses on delete cascade,
    title                      varchar(200) not null,
    duration_min               integer      not null,
    question_count             integer      not null,
    randomize                  boolean      not null,
    pass_mark                  integer      not null,
    attempts_allowed           integer      not null,
    opens_at                   date,
    closes_at                  date,
    show_correction            boolean      not null,
    room_only                  boolean      not null,
    requires_admin_validation  boolean      not null
);

create table exam_questions (
    exam_id      bigint not null constraint fk_exam_questions_exam references exams on delete cascade,
    question_id  bigint not null constraint fk_exam_questions_question references questions on delete cascade,
    constraint pk_exam_questions primary key (exam_id, question_id)
);
create index ix_exam_questions_question on exam_questions (question_id);

create table exam_attempts (
    id             bigint generated by default as identity primary key,
    exam_id        bigint      not null constraint fk_attempts_exam references exams on delete cascade,
    user_id        bigint      not null constraint fk_attempts_user references users on delete cascade,
    number         integer     not null,
    status         varchar(20) not null constraint ck_attempts_status check (status in ('EN_COURS', 'SOUMIS')),
    started_at     timestamp(6) with time zone not null,
    ends_at        timestamp(6) with time zone not null,
    submitted_at   timestamp(6) with time zone,
    last_saved_at  timestamp(6) with time zone,
    session_token  varchar(64),
    question_ids   jsonb       not null,
    option_orders  jsonb       not null,
    answers        jsonb       not null,
    flagged        jsonb       not null,
    current_index  integer     not null,
    tab_switches   integer     not null,
    score          integer,
    passed         boolean,
    ip_address     varchar(64)
);
create index ix_attempts_exam_user on exam_attempts (exam_id, user_id);
create index ix_attempts_user on exam_attempts (user_id);
create index ix_attempts_status_ends on exam_attempts (status, ends_at);

create table submissions (
    id            bigint generated by default as identity primary key,
    user_id       bigint       not null constraint fk_submissions_user references users on delete cascade,
    course_id     bigint       not null constraint fk_submissions_course references courses on delete cascade,
    lesson_id     bigint       constraint fk_submissions_lesson references lessons on delete set null,
    task          varchar(200) not null,
    stored_file   varchar(255) not null,
    file_name     varchar(255) not null,
    status        varchar(20)  not null constraint ck_submissions_status check (status in ('A_CORRIGER', 'CORRIGE')),
    grade         integer,
    comment       text,
    submitted_at  timestamp(6) with time zone not null,
    graded_at     timestamp(6) with time zone
);
create index ix_submissions_course on submissions (course_id);
create index ix_submissions_user on submissions (user_id);

-- ---------------------------------------------------------------- Certification
create sequence certificate_code_seq start with 1000;

create table certificates (
    id              bigint generated by default as identity primary key,
    code            varchar(40)  not null constraint uk_certificates_code unique,
    user_id         bigint       not null constraint fk_certificates_user references users on delete cascade,
    course_id       bigint       not null constraint fk_certificates_course references courses on delete cascade,
    type            varchar(20)  not null constraint ck_certificates_type check (type in ('ATTESTATION', 'COMPETENCE')),
    holder_name     varchar(170) not null,
    score           integer,
    mention         varchar(40),
    issued_at       date         not null,
    status          varchar(20)  not null constraint ck_certificates_status check (status in ('VALIDE', 'REVOQUE', 'EN_ATTENTE')),
    signature       varchar(128) not null,
    revoked_reason  text,
    revoked_at      timestamp(6) with time zone
);
create index ix_certificates_user on certificates (user_id);
create index ix_certificates_course on certificates (course_id);

-- ---------------------------------------------------------------- Notifications
create table notifications (
    id          bigint generated by default as identity primary key,
    user_id     bigint       not null constraint fk_notifications_user references users on delete cascade,
    type        varchar(20)  not null constraint ck_notifications_type check (type in ('EXAM', 'LESSON', 'CERTIFICATE', 'ENROLLMENT', 'ACCOUNT', 'GRADE', 'COURSE')),
    title       varchar(200) not null,
    text        text,
    link        varchar(255),
    is_read     boolean      not null,
    created_at  timestamp(6) with time zone not null
);
create index ix_notifications_user on notifications (user_id, created_at desc);

-- ---------------------------------------------------------------- Site vitrine
create table news (
    id            bigint generated by default as identity primary key,
    slug          varchar(200) not null constraint uk_news_slug unique,
    title         varchar(200) not null,
    category      varchar(60),
    excerpt       varchar(500),
    body          text,
    image_url     varchar(255),
    published_at  date         not null,
    published     boolean      not null
);

create table partners (
    id        bigint generated by default as identity primary key,
    name      varchar(160) not null,
    logo_url  varchar(255),
    website   varchar(255),
    position  integer      not null
);

create table faq_items (
    id        bigint generated by default as identity primary key,
    question  varchar(300) not null,
    answer    text         not null,
    tag       varchar(60),
    position  integer      not null
);

create table site_settings (
    setting_key    varchar(80) primary key,
    setting_value  text
);

create table contact_messages (
    id          bigint generated by default as identity primary key,
    name        varchar(160) not null,
    phone       varchar(30),
    email       varchar(160),
    subject     varchar(120),
    message     text         not null,
    handled     boolean      not null,
    created_at  timestamp(6) with time zone not null
);
